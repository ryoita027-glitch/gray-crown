ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "prototype_artifacts" / "pixel_vslice_acceptance_v1"
EVIDENCE.mkdir(parents=True, exist_ok=True)
SAVE_KEY = "gray-crown-vslice-save-v1"


@contextlib.contextmanager
def served(root):
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, directory=str(root), **kwargs)
        def log_message(self, *args):
            pass
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Quiet)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield f"http://127.0.0.1:{server.server_port}/index.html"
    finally:
        server.shutdown()
        server.server_close()


def require(ok, message):
    if not ok:
        raise AssertionError(message)


def finish(page, limit=100):
    for _ in range(limit):
        if not page.locator("#dialogueBox").is_visible():
            return
        page.keyboard.press("Enter")
        page.wait_for_timeout(42)
    raise AssertionError("dialogue stalled")


def new_game(page, url):
    page.goto(url, wait_until="networkidle")
    page.locator("#titleNewGame").click()
    finish(page)
    require(page.evaluate("GC.State.get().map") == "village", "new game did not enter village")


def walk(page, destination):
    board = page.evaluate("""() => ({
      width:COLS,height:ROWS,blocked:Array.from({length:ROWS},(_,y)=>
      Array.from({length:COLS},(_,x)=>isBlocked(x,y)))})""")
    here = page.evaluate("({x:GC.State.get().x,y:GC.State.get().y})")
    start = (here["x"], here["y"])
    goal = tuple(destination)
    pending = deque([start])
    parent = {start: None}
    directions = [(0, -1, "ArrowUp"), (1, 0, "ArrowRight"),
                  (0, 1, "ArrowDown"), (-1, 0, "ArrowLeft")]
    while pending:
        x, y = pending.popleft()
        if (x, y) == goal:
            break
        for dx, dy, key in directions:
            n = (x + dx, y + dy)
            if 0 <= n[0] < board["width"] and 0 <= n[1] < board["height"] and not board["blocked"][n[1]][n[0]] and n not in parent:
                parent[n] = ((x, y), key)
                pending.append(n)
    require(goal in parent, f"no legal path from {start} to {goal}")
    keys = []
    node = goal
    while node != start:
        previous, key = parent[node]
        keys.append(key)
        node = previous
    for key in reversed(keys):
        before = page.evaluate("({x:GC.State.get().x,y:GC.State.get().y,map:GC.State.get().map})")
        page.keyboard.press(key)
        page.wait_for_timeout(145)
        after = page.evaluate("({x:GC.State.get().x,y:GC.State.get().y,map:GC.State.get().map})")
        require(after["map"] == before["map"] and
                (after["x"], after["y"]) != (before["x"], before["y"]),
                f"blocked or transitioned on {key}: {before} => {after}")


def test_main_v23_save(browser, candidate_url, main_dir):
    """The save is *generated by pinned production main runtime*, not hand-built JSON."""
    require(main_dir and main_dir.is_dir(), "pinned main v23 checkout missing")
    with served(main_dir) as main_url:
        source = browser.new_page(viewport={"width": 1365, "height": 900})
        new_game(source, main_url)
        require(source.evaluate("GC.Save.save(true) === true"), "main v23 cannot save")
        raw = source.evaluate("localStorage.getItem(" + json.dumps(SAVE_KEY) + ")")
        original = json.loads(raw)
        require(original["schema"] == 23, "main baseline is not save schema 23")
        proof = {"source_commit": "d689aabb5146c9f45466a4f74f397e664c08fb4f",
                 "source": "real production main Chromium Save.save(true)",
                 "sha256": hashlib.sha256(raw.encode()).hexdigest(),
                 "source_map": original["map"], "source_stage": original["story"]["stage"]}
        source.close()
        destination = browser.new_page(viewport={"width": 1365, "height": 900})
        destination.add_init_script("localStorage.setItem(" + json.dumps(SAVE_KEY) + "," + json.dumps(raw) + ")")
        destination.goto(candidate_url, wait_until="networkidle")
        require(destination.locator("#titleContinue").is_enabled(), "main v23 Continue disabled")
        destination.locator("#titleContinue").click()
        finish(destination)
        restored = destination.evaluate("""() => ({
          schema:GC.State.get().schema,map:GC.State.get().map,
          stage:GC.State.get().story.stage,party:GC.State.get().party.map(p=>p.id)
        })""")
        require(restored["schema"] == 23 and
                restored["map"] == original["map"] and
                restored["stage"] == original["story"]["stage"],
                "main v23 state changed on candidate Continue")
        require(len(restored["party"]) == 4, "main v23 party not restored")
        require(destination.evaluate("GC.Save.save(true) === true"), "candidate cannot re-save v23")
        proof["result"] = "PASS: source-generated main save / Continue / candidate re-save"
        (EVIDENCE / "main_v23_save_provenance.json").write_text(json.dumps(proof, ensure_ascii=False, indent=2), encoding="utf8")
        destination.screenshot(path=str(EVIDENCE / "phase0_main_v23_continue.png"), full_page=True)
        destination.close()


def test_pingpong(browser, url):
    page = browser.new_page(viewport={"width": 1365, "height": 900})
    new_game(page, url)
    move = page.evaluate("""() => {
      const s=GC.State.get();
      for(const [dx,dy,k,back] of [[0,-1,'ArrowUp','ArrowDown'],[1,0,'ArrowRight','ArrowLeft'],[0,1,'ArrowDown','ArrowUp'],[-1,0,'ArrowLeft','ArrowRight']]){
        if(!isBlocked(s.x+dx,s.y+dy))return{k,back}
      }
      return null
    }""")
    require(move, "no walkable neighboring tile for ping-pong reproduction")
    for _ in range(9):
        for key in (move["k"], move["back"]):
            prev = page.evaluate("({x:GC.State.get().x,y:GC.State.get().y})")
            page.keyboard.press(key)
            page.wait_for_timeout(145)
            now = page.evaluate("({x:GC.State.get().x,y:GC.State.get().y})")
            require(now != prev, f"2-cell loop movement failed: {prev} {key}")
    result = page.evaluate("""() => {
      const s=GC.State.get(), pts=[[s.x,s.y],...partyTrailPoints()];
      return {positions:pts, unique:new Set(pts.map(p=>p.join(','))).size,
              walkable:pts.slice(1).every(p=>!isBlocked(p[0],p[1])),
              trailDistinct:new Set(s.trail.map(p=>p.join(','))).size}
    }""")
    require(result["trailDistinct"] <= 2, "test never reproduced repeated two-cell trail")
    require(result["unique"] == 4 and result["walkable"],
            "ping-pong party anchors overlap or enter blocked tile: " + repr(result))
    page.screenshot(path=str(EVIDENCE / "phase0_two_cell_pingpong.png"), full_page=True)
    page.close()


def test_defeat_and_battle(browser, url):
    page = browser.new_page(viewport={"width": 1365, "height": 900})
    new_game(page, url)
    walk(page, (12, 7))
    page.keyboard.press("ArrowUp")
    page.wait_for_timeout(150)
    page.keyboard.press("Enter")
    finish(page)
    require(page.evaluate("GC.State.get().story.stage") == "01_appointed", "appointment blocked")
    walk(page, (11, 1))
    page.keyboard.press("ArrowUp")
    page.wait_for_timeout(150)
    finish(page)
    require(page.evaluate("GC.State.get().map") == "road", "road not reached")
    walk(page, (11, 7))
    # Set up a valid losing-party edge state (one injured survivor, three KO)
    # while still outside the battle. No developer instant win/invincibility,
    # no direct calls to enemyTurn(), battleLose() or scripted result APIs.
    page.evaluate("""() => {
      const party=GC.State.get().party;
      party.forEach((p,i)=>{p.hp=i===0?1:0;p.guard=false});
      GC.Render.World.renderHud();
    }""")
    before = page.evaluate("""() => ({
      gold:GC.State.get().gold,levels:GC.State.get().party.map(p=>p.level),
      exp:GC.State.get().party.map(p=>p.exp)
    })""")
    for _ in range(2):
        page.keyboard.press("ArrowUp")
        page.wait_for_timeout(160)
        if page.evaluate("GC.State.get().battle?.id") == "wolves":
            break
    require(page.evaluate("GC.State.get().battle?.id") == "wolves",
            "real world wolf trigger missing")
    heroes = page.locator("#partyBattleLine .battle-hero")
    require(heroes.count() == 4, "battle does not show four heroes")
    sizing = page.evaluate("""() => {
      const heroes=[...document.querySelectorAll('#partyBattleLine .battle-hero')];
      return {size:getComputedStyle(heroes[0]).backgroundSize,
              spacing:heroes[1].getBoundingClientRect().left-heroes[0].getBoundingClientRect().left,
              stage:document.querySelector('#battleStage').getBoundingClientRect().height}
    }""")
    require(sizing["stage"] >= 300 and sizing["spacing"] >= 70 and
            sizing["size"] == "480px 320px", "battle layout failed: " + repr(sizing))
    page.screenshot(path=str(EVIDENCE / "phase0_battle_layout.png"), full_page=True)
    page.wait_for_timeout(750)
    require(page.locator('[data-battle="guard"]').is_visible(), "guard command absent")
    page.locator('[data-battle="guard"]').click()
    page.wait_for_function("() => GC.State.get().battle === null", timeout=10000)
    page.wait_for_function("() => document.querySelector('#battlePanel').classList.contains('hidden')", timeout=10000)
    require(page.locator("#dialogueBox").is_visible(), "defeat recovery feedback absent")
    # Text is revealed one glyph at a time after the panel closes.
    # Assert the actual final in-game wording, not an early partial frame.
    page.wait_for_function("""() =>
      document.querySelector('#dialogueText')?.textContent.includes('安全な場所まで退いた')
    """, timeout=8000)
    page.screenshot(path=str(EVIDENCE / "phase0_defeat_recovery.png"), full_page=True)
    finish(page)
    after = page.evaluate("""() => ({
      map:GC.State.get().map,party:GC.State.get().party.map(p=>({hp:p.hp,maxHp:p.maxHp,mp:p.mp,maxMp:p.maxMp})),
      gold:GC.State.get().gold,levels:GC.State.get().party.map(p=>p.level),
      exp:GC.State.get().party.map(p=>p.exp),battle:GC.State.get().battle
    })""")
    require(after["map"] == "road" and after["battle"] is None, "defeat did not return to road")
    require(all(p["hp"] == p["maxHp"] and p["mp"] == p["maxMp"] for p in after["party"]),
            "defeat failed HP/MP recovery")
    require(after["gold"] == before["gold"] and
            after["levels"] == before["levels"] and after["exp"] == before["exp"],
            "defeat corrupted progression/currency")
    require(page.evaluate("GC.State.get().world.defeatedSymbols.wolf") is not True,
            "defeated symbol marked despite battle loss")
    page.close()


def test_mobile_portraits(browser, url):
    page = browser.new_page(viewport={"width": 390, "height": 844}, device_scale_factor=1)
    new_game(page, url)
    metrics = page.evaluate("""() => {
      const e=document.querySelector('#mobileAct'),style=getComputedStyle(e);
      const range=document.createRange();range.selectNodeContents(e);
      return {whiteSpace:style.whiteSpace,rects:range.getClientRects().length,
              fits:e.scrollWidth<=e.clientWidth+1,
              overflowing:document.documentElement.scrollWidth>innerWidth+2}
    }""")
    require(metrics["whiteSpace"] == "nowrap" and metrics["rects"] == 1 and
            metrics["fits"] and not metrics["overflowing"],
            "mobile action button broken: " + repr(metrics))
    page.screenshot(path=str(EVIDENCE / "phase0_mobile_touch_controls.png"), full_page=True)
    # Same actor/line in both real dialogue modes, kept separate and comparable.
    page.evaluate("say('カレン','同じ台詞のPortrait ON比較です。')")
    require(page.locator("#speakerPortrait").is_visible(), "Portrait ON missing")
    page.screenshot(path=str(EVIDENCE / "phase0_portrait_on.png"), full_page=True)
    finish(page)
    page.evaluate("say('カレン','同じ台詞のPortrait OFF比較です。',[],null,{portraitMode:'disabled'})")
    require(not page.locator("#speakerPortrait").is_visible(), "Portrait OFF not honored")
    page.screenshot(path=str(EVIDENCE / "phase0_portrait_off.png"), full_page=True)
    finish(page)
    page.close()


def main():
    baseline = os.environ.get("GRAY_CROWN_MAIN_V23_DIR")
    with served(ROOT) as url:
        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            if baseline:
                test_main_v23_save(browser, url, Path(baseline).resolve())
            else:
                print("main v23 checkout absent: compatibility gate not run (local only)")
            test_pingpong(browser, url)
            test_defeat_and_battle(browser, url)
            test_mobile_portraits(browser, url)
            browser.close()
    print("PHASE 0 REMAINING E2E PASS: main save, ping-pong, battle/defeat, mobile, portrait A/B")


if __name__ == "__main__":
    main()
